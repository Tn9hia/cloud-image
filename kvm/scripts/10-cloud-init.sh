#!/usr/bin/env bash
# Cấu hình cloud-init theo platform (PLATFORM=openstack|cloudstack).
set -euxo pipefail

CFG_DIR=/etc/cloud/cloud.cfg.d

# Dọn config installer để lại. Quan trọng nhất trên Ubuntu:
#  - 99-installer.cfg: ép datasource None + user-data lúc install
#  - subiquity-disable-cloudinit-networking.cfg: tắt network config của cloud-init
rm -f \
  "${CFG_DIR}/99-installer.cfg" \
  "${CFG_DIR}/90-installer-network.cfg" \
  "${CFG_DIR}/subiquity-disable-cloudinit-networking.cfg" \
  /etc/cloud/ds-identify.cfg \
  /etc/cloud/cloud-init.disabled

case "${PLATFORM}" in
  openstack)  DATASOURCES="ConfigDrive, OpenStack, None" ;;
  cloudstack) DATASOURCES="ConfigDrive, CloudStack, None" ;;
  *) echo "Unsupported PLATFORM: ${PLATFORM}" >&2; exit 1 ;;
esac

install -m 0644 -o root -g root /tmp/99_platform.cfg "${CFG_DIR}/99_${PLATFORM}.cfg"
rm -f /tmp/99_platform.cfg

# Ubuntu: đồng bộ debconf để 90_dpkg.cfg không lệch với config của mình
# (99_${PLATFORM}.cfg vẫn thắng vì load sau).
if [ "${OS_FAMILY}" = "debian" ]; then
  echo "cloud-init cloud-init/datasources multiselect ${DATASOURCES}" | debconf-set-selections
  DEBIAN_FRONTEND=noninteractive dpkg-reconfigure -f noninteractive cloud-init
fi

# CloudStack: Reset Password / Reset SSH Key trên UI chỉ có tác dụng nếu module
# set_passwords và ssh chạy mỗi lần boot. Không sed /etc/cloud/cloud.cfg (file của package,
# dễ bị conflict khi upgrade) mà sinh file override trong cloud.cfg.d từ chính list của distro.
if [ "${PLATFORM}" = "cloudstack" ]; then
python3 - <<'PY'
import yaml

ALWAYS = {"set_passwords", "ssh"}
SECTIONS = ("cloud_init_modules", "cloud_config_modules", "cloud_final_modules")

with open("/etc/cloud/cloud.cfg") as f:
    cfg = yaml.safe_load(f)

override, found = {}, set()
for section in SECTIONS:
    modules = cfg.get(section) or []
    new, changed = [], False
    for mod in modules:
        name = mod if isinstance(mod, str) else mod[0]
        key = name.replace("-", "_")
        if key in ALWAYS:
            new.append([name, "always"])
            found.add(key)
            changed = True
        else:
            new.append(mod)
    if changed:
        override[section] = new

missing = ALWAYS - found
if missing:
    raise SystemExit(f"modules not found in /etc/cloud/cloud.cfg: {sorted(missing)}")

with open("/etc/cloud/cloud.cfg.d/98_module_frequency.cfg", "w") as f:
    f.write("# Generated by Packer from /etc/cloud/cloud.cfg at build time.\n")
    f.write("# set_passwords + ssh run on every boot (CloudStack reset password / SSH key).\n")
    yaml.safe_dump(override, f, default_flow_style=False, sort_keys=False)
PY
cat "${CFG_DIR}/98_module_frequency.cfg"
fi

# Kiểm tra cú pháp YAML toàn bộ config hệ thống.
python3 - <<'PY'
import glob, yaml
for path in ["/etc/cloud/cloud.cfg"] + sorted(glob.glob("/etc/cloud/cloud.cfg.d/*.cfg")):
    with open(path) as f:
        yaml.safe_load(f)
    print("OK", path)
PY
cloud-init schema --system || echo "WARNING: cloud-init schema --system reported issues"

# Đảm bảo các unit cloud-init được enable (tên unit khác nhau giữa các version cloud-init).
for unit in cloud-init-main cloud-init-local cloud-init cloud-init-network cloud-config cloud-final; do
  if systemctl list-unit-files "${unit}.service" --no-legend | grep -q "^${unit}.service"; then
    systemctl enable "${unit}.service"
  fi
done
